import { useTranslation } from 'react-i18next';
import { EmailLink } from './EmailLink';
import { LegalLayout } from './LegalLayout';
import { OPERATOR } from './operator';

// LEGAL_DOCS: добавлено 2026-09-25
/** Политика возврата денежных средств, открывается по `#/refund`. */
interface RefundPolicyProps {
  onBack: () => void;
}

export function RefundPolicy({ onBack }: RefundPolicyProps) {
  const { t } = useTranslation();

  return (
    <LegalLayout title={t('legal.refundTitle')} updatedAt={OPERATOR.updatedAt} onBack={onBack}>
      <p>
        Настоящая Политика описывает условия и порядок возврата денежных средств, уплаченных за доступ
        к сервису CONEXYAI ({OPERATOR.site}).
      </p>

      <h2>1. Общие условия</h2>
      <p>
        1.1. Возврат средств возможен при обращении Пользователя в течение{' '}
        <strong>14 (четырнадцати) календарных дней</strong> с момента оплаты Тарифа, при условии что
        доступ к оплаченным функциям Сервиса фактически не использовался или использован в
        незначительном объёме (см. п. 2.2).
      </p>

      <h2>2. Когда возврат не производится</h2>
      <p>
        2.1. Возврат не производится, если с момента активации Тарифа прошло более 14 календарных
        дней.
      </p>
      <p>
        2.2. Возврат не производится либо производится частично (пропорционально неиспользованному
        лимиту), если Пользователь уже израсходовал существенную часть лимитов Тарифа (запросов,
        токенов, задач в режимах чата, агентских задач, Coder или Cowork) — точный порог указывается
        при рассмотрении обращения индивидуально, исходя из объёма использования.
      </p>
      <p>
        2.3. Возврат не производится, если доступ был ограничен или прекращён из-за нарушения
        Пользователем условий Оферты (п. 4.3–4.4 Оферты) или законодательства РФ.
      </p>

      <h2>3. Как оформить возврат</h2>
      <p>
        3.1. Для возврата средств Пользователь направляет запрос на email <EmailLink /> с указанием:
      </p>
      <ul>
        <li>email/логина учётной записи, с которой производилась оплата;</li>
        <li>даты и суммы платежа;</li>
        <li>причины запроса на возврат.</li>
      </ul>
      <p>
        3.2. Исполнитель рассматривает обращение в течение <strong>10 (десяти) рабочих дней</strong> с
        момента получения запроса.
      </p>
      <p>
        3.3. При положительном решении денежные средства возвращаются на карту/счёт, с которого
        производилась оплата, через платёжную систему ЮKassa, в срок до 10 рабочих дней с момента
        принятия решения (фактический срок зачисления зависит от банка Пользователя).
      </p>

      <h2>4. Контакты</h2>
      <p>
        По всем вопросам, связанным с возвратом средств:
        <br />
        Email: <EmailLink />
        <br />
        Телефон: {OPERATOR.phone}
      </p>
    </LegalLayout>
  );
}
