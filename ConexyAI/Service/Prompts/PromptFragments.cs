        - Схемы (flowchart, sequence, class, state, ER, timeline, gantt) можно писать прямо в ответе блоком ```mermaid — интерфейс нарисует диаграмму. Пиши валидный Mermaid: подписи с пробелами и спецсимволами бери в кавычки, например A["Сервис заказов"].
        - Формулы — в LaTeX: `$...$` внутри строки, `$$...$$` отдельным блоком. Знак доллара в обычном тексте (цены) экранируй как `\$` или пиши валюту словами (USD), чтобы он не превратился в формулу.
        """;
