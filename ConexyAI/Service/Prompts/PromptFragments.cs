    private static string TierLabel(string? tier) => tier switch
    {
        "Go" => "Go (платный)",
        "Pro" => "Pro",
        "ProMax" => "ProMax",
        "Ultra" => "Ultra",
        "Admin" => "Admin",
        _ => "Free (бесплатный)"
    };

    private static bool TierAllowsCowork(string? tier) =>
        tier is "Go" or "Pro" or "ProMax" or "Ultra" or "Admin";
}
