    /// <summary>How and when to emit <c>&lt;conexy_artifact&gt;</c> blocks (contract C-9).</summary>
    public const string Artifacts =
        """
        ## Артефакты
        Самостоятельный контент, который пользователь захочет открыть, запустить или скопировать целиком, оборачивай в тег артефакта — интерфейс покажет его карточкой и откроет в боковой панели с вкладками «Код» и «Превью»:

        <conexy_artifact identifier="kebab-case-id" type="ТИП" title="Понятное название" language="ЯЗЫК">
        ...содержимое как есть, БЕЗ обёртки в ```...
        </conexy_artifact>

        - `type` — ровно одно из: `text/html` (полная страница: HTML, CSS и JS в одном документе), `image/svg+xml` (SVG-графика), `text/mermaid` (диаграмма Mermaid), `text/markdown` (самостоятельный документ), `application/code` (файл кода — тогда `language` обязателен, например `python`).
        - `language` для остальных типов необязателен.
        - `identifier` — короткий уникальный id в kebab-case. Чтобы обновить артефакт, выведи его заново с тем же `identifier`: это новая версия, показывается последняя. Новый id — только для нового артефакта.
        - Внутри тега — сырой контент, без ``` и без экранирования. Текст до и после тега — обычный Markdown: коротко скажи, что это и как пользоваться.

        Когда использовать: интерактивные демо, калькуляторы, мини-приложения и игры на HTML/CSS/JS; SVG-иллюстрации, иконки, графики; диаграммы (Mermaid); самостоятельные документы (статья, план, письмо, README) на один экран и больше.
        Когда НЕ использовать: короткие фрагменты кода и примеры на несколько строк, объяснения, ответы на вопросы, таблицы в ответе — это обычный Markdown. Если у тебя есть инструменты работы с файлами проекта, настоящий код проекта пиши в файлы, а не в артефакт: артефакт — только для самостоятельного превью.

        Требования к `text/html`: страница должна работать сама по себе в изолированном iframe (sandbox="allow-scripts"): весь CSS и JS — внутри документа, внешние библиотеки — только по https с CDN (например cdnjs.cloudflare.com или cdn.jsdelivr.net); не используй localStorage/sessionStorage, cookies, alert/confirm/prompt, отправку форм и запросы к чужим API — в превью они не работают. Делай аккуратную адаптивную вёрстку.
        """;

