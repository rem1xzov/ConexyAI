    // Теперь прямо запрещено отрицать существование по памяти и требуется искать в этом же ответе.
    /// <summary>Knowledge-first fact-checking rules for the chat models' <c>web_search</c> tool.</summary>
    public const string SmartSearch =
        """
        Тебе доступен инструмент `web_search`. Правила работы:
        1. Твои знания ограничены по времени. Всё, что появилось после обучения — новые модели, версии, продукты, релизы, люди, события, цены — ты можешь не знать. «Не помню» — это НЕ «не существует». Незнание — это повод искать, а не повод отрицать.
        2. КАТЕГОРИЧЕСКИ запрещено утверждать, что чего-то не существует, не вышло, не бывает или «такой модели/версии/продукта нет», только потому, что ты об этом не помнишь. Сначала проверь через `web_search` и только потом отвечай.
        3. Никогда не выдумывай факты — даты, цены, версии, числа, названия, события, цитаты, законы, характеристики. Если не знаешь или не уверен — сразу, в этом же ответе, скажи «не уверен, проверю в интернете», вызови `web_search` и ответь по найденному. Не обещай проверить позже и не проси пользователя попросить тебя поискать.
        4. Обязательно ищи, когда вопрос касается: текущей даты/времени, недавних событий, актуальных версий/цен/статусов, новинок и релизов, названий моделей/продуктов/компаний — и вообще всего, чего может не быть в твоих обучающих данных.
        5. Опирайся на собственные знания только для устойчивых, общеизвестных вещей (определения, математика, код) и не вызывай поиск ради самого поиска.
        6. Ответ строй на содержимом выдачи, а не на догадках. Если поиск не дал ответа — так и скажи, не придумывая.
        """;

    // SMART_SEARCH_FORCE: добавлено 2026-10-04 — если вопрос явно про свежие/версионные/рыночные факты,
    // первый раунд чата принудительно уходит в web_search (tool_choice=required), чтобы flash не успел
    // ответить из памяти (и не отрицал существование новинки). Устойчивые знания не трогаем.
    private static readonly System.Text.RegularExpressions.Regex FreshInfoSignal = new(
        @"(\bv?\d+\.\d+\b)" +
        @"|(\b20[2-9]\d\b)" +
        @"|(\bмодел(ь|и|ей|ью|ям|ях)\b)" +
        @"|(\bmodels?\b)" +
        @"|(\bверси(я|и|ю|ей|й|ям|ях|онн\w*)\b|version)" +
        @"|(релиз\w*|release)" +
        @"|(вышл\w*|выпуст\w*|выпущен\w*)" +
        @"|(новинк\w*|новост\w*|\bnews\b)" +
        @"|(актуальн\w*)" +
        @"|(последн\w*\s+(верси\w*|релиз\w*|модел\w*|обновлен\w*|новост\w*))" +
        @"|(\bцен[аыуе]\b|\bцену\b|стоимост\w*|\bprice\b)" +
        @"|(существу\w*)" +
        @"|(курс\s+(валют|доллар|евро|акци))",
        System.Text.RegularExpressions.RegexOptions.IgnoreCase | System.Text.RegularExpressions.RegexOptions.Compiled);

    /// <summary>
    /// True when the question is about something that may have changed or be newer than the model's
    /// training data (a model/version/release, a price, a recent event) — then the first chat round
    /// must search the web before answering instead of trusting memory.
    /// </summary>
    public static bool RequiresFreshInfo(string? prompt) =>
        !string.IsNullOrWhiteSpace(prompt) && FreshInfoSignal.IsMatch(prompt);

