        Самостоятельный контент, который пользователь захочет открыть, запустить или скопировать целиком, оборачивай в тег артефакта — интерфейс покажет его карточкой и откроет в боковой панели с вкладками «Код» и «Превью»:

        <conexy_artifact identifier="kebab-case-id" type="ТИП" title="Понятное название" language="ЯЗЫК">
        ...содержимое как есть, БЕЗ обёртки в ```...
        </conexy_artifact>

        - `type` — ровно одно из: `text/html` (полная страница: HTML, CSS и JS в одном документе), `image/svg+xml` (SVG-графика), `text/mermaid` (диаграмма Mermaid), `text/markdown` (самостоятельный документ), `application/code` (файл кода — тогда `language` обязателен, например `python`).
